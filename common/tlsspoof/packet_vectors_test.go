func TestSpoofFrameVectors(t *testing.T) {
	for _, vector := range spoofFrameVectors {
		frame, err := buildSpoofFrame(vector.method, netip.MustParseAddrPort(vector.source), netip.MustParseAddrPort(vector.target),
			0x12345678, 0x9abcdef0, vector.timestamp, nil, []byte("forged-client-hello"))
		require.NoError(t, err)
		require.Equal(t, vector.frame, hex.EncodeToString(frame), "%s %s timestamp %d", vector.family, vector.method, vector.timestamp)
	}
}
